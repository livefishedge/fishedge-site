const assert = require('node:assert/strict');
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || '/home/gzheng/.openclaw/tools/node-v22.22.0/lib/node_modules/openclaw/node_modules/playwright-core');
const url = process.env.PLANNER_URL || 'http://127.0.0.1:8766/trip-planner/briefing-viewer.html?region=usec_md';
(async () => {
  const browser = await chromium.launch({headless:true, executablePath:process.env.CHROMIUM_PATH || '/home/gzheng/.cache/ms-playwright/chromium-1223/chrome-linux64/chrome', args:['--no-sandbox']});
  try {
    const page=await browser.newPage({viewport:{width:1200,height:850}});
    const errors=[];page.on('pageerror',e=>errors.push(e.message));
    await page.goto(url);
    await page.waitForFunction(()=>document.querySelector('#bv-frame-label').textContent.includes(' ET'),{timeout:30000});
    await page.waitForTimeout(1800);
    const select=()=>page.locator('select[data-map-field]');
    const pixels=()=>page.evaluate(()=>{
      const c=document.querySelector('.bv-streamlines-canvas'),d=c.getContext('2d').getImageData(0,0,c.width,c.height).data;
      let n=0;for(let i=3;i<d.length;i+=4)if(d[i]>100)n++;return n;
    });
    await page.locator('[data-wave-motion]').uncheck();
    for(const key of ['wave_height_ft','swell_height_ft','wind_wave_height_ft']){
      await select().selectOption(key);await page.waitForTimeout(150);
      assert(await pixels()>1000, key+' must paint pixels, not merely a legend');
    }
    await select().selectOption('');await page.waitForTimeout(150);
    assert.equal(await pixels(),0,'None must clear fill');
    await page.locator('[data-preset=weather]').click();
    await page.locator('.bv-layer-details summary').click();
    await page.locator('[data-scalar=dew_point_f]').click();
    assert(await page.locator('.bv-layer-details').evaluate(e=>e.open),'Details stays open after selection');
    assert.equal(await select().inputValue(),'dew_point_f');
    await page.locator('[data-preset=fishing]').click();
    await page.locator('[data-preset=weather]').click();
    assert.equal(await select().inputValue(),'dew_point_f','view remembers field');
    await page.locator('[data-reset-view]').click();
    assert.equal(await select().inputValue(),'visibility_mi');
    await page.locator('[data-preset=sea]').click();
    await select().selectOption('wave_height_ft');
    await page.locator('[data-wave-motion]').check();
    const waveKey = page.locator('#bv-wave-key');
    const waveKeyBefore = await waveKey.boundingBox();
    await page.mouse.move(waveKeyBefore.x + 60, waveKeyBefore.y + 10);
    await page.mouse.down(); await page.mouse.move(waveKeyBefore.x + 90, waveKeyBefore.y + 25); await page.mouse.up();
    const waveKeyAfter = await waveKey.boundingBox();
    assert(waveKeyAfter.x !== waveKeyBefore.x || waveKeyAfter.y !== waveKeyBefore.y,'Wave Motion card is draggable');
    const waveFrame = async()=>page.evaluate(()=>{const c=document.querySelector('.bv-streamlines-canvas'),d=c.getContext('2d').getImageData(0,0,c.width,c.height).data;let s=0;for(let i=0;i<d.length;i+=4){const p=i/4;s=(s+(p%997)*d[i+3]+d[i]*3+d[i+1]*5+d[i+2]*7)%1000000007}return s});
    await page.waitForTimeout(900); const waveBefore=await waveFrame(); await page.waitForTimeout(650); const waveAfter=await waveFrame();
    assert(waveBefore>0 && waveAfter>0 && waveBefore!==waveAfter,'wave motion changes rendered crests');
    const frameTiming=await page.evaluate(()=>new Promise(resolve=>{
      const samples=[];let prev=performance.now();let count=0;
      const tick=now=>{samples.push(now-prev);prev=now;if(++count<30)requestAnimationFrame(tick);else resolve(samples.slice(1));};
      requestAnimationFrame(tick);
    }));
    const sortedTiming=[...frameTiming].sort((a,b)=>a-b);
    assert(sortedTiming[Math.floor(sortedTiming.length*0.95)]<120,'wave animation frame time remains bounded');
    await page.mouse.click(600,400);
    assert(await page.locator('#bv-wave-readout').isVisible(),'map click opens readout');
    assert(/°[WE], .*°[NS]/.test(await page.locator('#bv-wave-readout [data-readout-title]').innerText()),'readout uses signed coordinates');
    assert(/forecast/.test(await page.locator('#bv-wave-readout [data-readout-body]').innerText()),'readout shows forecast time');
    const readoutText = await page.locator('#bv-wave-readout [data-readout-body]').innerText();
    assert(/Significant Wave Height/.test(readoutText),'readout keeps the full significant-wave label');
    assert(/Swell|Wave Height \(Chop\)|Wind/.test(readoutText),'readout includes checked supporting layers');
    assert.equal(await page.locator('#bv-click-marker').evaluate(e=>getComputedStyle(e).display),'block','clicked location marker visible');
    await page.locator('.bv-readout-toggle').click();
    assert(await page.locator('#bv-wave-readout').evaluate(e=>e.classList.contains('is-collapsed')),'readout can collapse');
    assert.equal(await page.locator('.bv-readout-toggle').evaluate(e=>getComputedStyle(e).display),'none','collapsed readout hides plus control');
    assert.equal(await page.locator('.bv-readout-toggle').innerText(),'−','readout toggle never changes to plus');
    await page.locator('#bv-wave-readout').click();
    assert(!(await page.locator('#bv-wave-readout').evaluate(e=>e.classList.contains('is-collapsed'))),'collapsed readout expands from card click');
    const readoutBeforeDrag = await page.locator('#bv-wave-readout').boundingBox();
    await page.mouse.move(readoutBeforeDrag.x + 40, readoutBeforeDrag.y + 20);
    await page.mouse.down(); await page.mouse.move(readoutBeforeDrag.x + 70, readoutBeforeDrag.y + 35); await page.mouse.up();
    const readoutAfterDrag = await page.locator('#bv-wave-readout').boundingBox();
    assert(readoutAfterDrag.x !== readoutBeforeDrag.x || readoutAfterDrag.y !== readoutBeforeDrag.y,'lat/lon readout is draggable');
    const desktopRanges = await page.locator('.bv-ranges').boundingBox();
    const desktopStrip = await page.locator('#bv-active-layer-strip').boundingBox();
    assert(desktopRanges.x >= desktopStrip.x + desktopStrip.width - 2,'desktop colorbar is to the right of layer controls');
    await page.locator('[data-preset=tides]').click();
    assert.equal(await select().inputValue(),'','Tides opens station-first');
    await page.waitForTimeout(250);
    assert(await page.locator('#bv-station-popup').isVisible());
    for(const marker of await page.locator('.bv-station-marker').all()){
      await marker.evaluate(e=>e.click());
      assert(!/unavailable|^—$/.test(await page.locator('#bv-tide-latest').innerText()));
      assert((await page.locator('#bv-tide-svg polyline').first().getAttribute('points')).length>10);
    }
    await page.locator('[data-preset=fishing]').click();
    await page.waitForTimeout(500);
    assert(await page.locator('input[data-layer=current]').first().isChecked(),'Fishing keeps Forecast Current checked');
    assert(!(await page.locator('input[data-layer=current]').first().isDisabled()),'Forecast Current has source data');
    const currentPixels = await page.locator('.bv-streamlines-canvas').evaluate(c=>{const d=c.getContext('2d').getImageData(0,0,c.width,c.height).data;let n=0;for(let i=3;i<d.length;i+=4)if(d[i]>30)n++;return n});
    assert(currentPixels>100,'Forecast Current renders streamlines');
    await page.setViewportSize({width:390,height:844});
    await page.locator('[data-preset=weather]').click();
    await page.locator('.bv-layer-details summary').click();
    const box=await page.locator('.bv-details-panel').boundingBox();
    assert(box.x>=0 && box.x+box.width<=390,'Details fits mobile');
    assert(!(await page.locator('#bv-time').isVisible()),'legacy 7-day freshness banner is removed');
    const ranges = await page.locator('.bv-ranges').boundingBox();
    const framebar = await page.locator('.bv-framebar').boundingBox();
    const dateRow = await page.locator('.bv-frame-date').boundingBox();
    const activeStrip = await page.locator('#bv-active-layer-strip').boundingBox();
    assert(framebar.y + framebar.height <= dateRow.y + 1,'playback row precedes forecast date row');
    assert(dateRow.y + dateRow.height <= activeStrip.y + 1,'forecast date row precedes layer row');
    assert(ranges.x >= activeStrip.x + activeStrip.width - 2 && Math.abs(ranges.y - activeStrip.y) < 2,'colorbar shares the selector row');
    assert(!/Color map:/.test(await page.locator('.bv-ranges-title').innerText()),'colorbar has no duplicate Color map label');
    await page.screenshot({path:'/tmp/planner-audit-mobile.png'});
    assert.deepEqual(errors,[]);
    console.log('PASS: scalar pixels, wave motion, None, Details persistence, view memory/reset, map readout/marker, 8 station charts, mobile bounds, no page errors');
  } finally { await browser.close(); }
})().catch(e=>{console.error(e);process.exitCode=1});
